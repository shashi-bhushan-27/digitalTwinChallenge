"""Worked what-if examples with plots (results/twin/example_*.png, docs/twin_examples.md).

    uv run python -m twin.examples

Patients are picked from the test split to illustrate: meal options with blocked choices, a
post-dinner walk, a sulfonylurea hypoglycaemia warning, and a kidney-limited drug change.
"""

from __future__ import annotations

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

from common import config
from data_gen.generate import load_configs
from twin import constraints as C
from twin import estimate as E
from twin import whatif as W
from twin.card import twin_card
from twin.model import Observed
from twin.validate import load_tables

RES = config.REPO_ROOT / "results" / "twin"


def _plot(ax, outcomes: list[tuple[str, W.Outcome, str]], title: str, t_now: pd.Timestamp) -> None:
    ax.axhspan(70, 180, color="#e9f3ea", zorder=0)
    ax.axhline(180, color="#c0392b", lw=0.7, ls="--")
    ax.axhline(70, color="#c0392b", lw=0.7, ls=":")
    for label, o, col in outcomes:
        h = (o.trajectory["timestamp"] - t_now).dt.total_seconds() / 3600
        ax.plot(h, o.trajectory["glucose_mgdl"], color=col, lw=2, label=f"{label} (peak {o.peak:.0f}, low {o.trough:.0f})")
    ax.set_xlabel("hours from now")
    ax.set_ylabel("glucose (mg/dL)")
    ax.set_title(title, fontsize=9)
    ax.legend(fontsize=7, frameon=False, loc="upper right")


def main() -> None:
    cfgs = load_configs()
    pc = cfgs["physiology"]
    tcfg = config.load("twin")
    lib = config.load("meal_library")["plates"]
    by_id = {p["id"]: p for p in lib}
    tabs, _ = load_tables(cfgs)
    pts = tabs["patients"].merge(tabs["splits"], on="patient_id")
    test = pts[pts["split"] == "test"]
    meds = tabs["medications"]
    su_ids = set(meds.loc[meds["drug_class"] == "sulfonylurea", "patient_id"])
    met_ids = set(meds.loc[meds["drug"] == "metformin", "patient_id"])

    hp = RES / "hypo_scenario.csv"
    flagged = set()
    if hp.exists() and hp.stat().st_size > 2:
        h = pd.read_csv(hp)
        flagged = set(h.loc[h["twin_flag"], "patient_id"]) or set(h.loc[h["twin_caution"], "patient_id"])

    def pick(cond, fallback):
        c = test[cond(test)]
        return (c if len(c) else pts[fallback(pts)]).iloc[0]["patient_id"]

    choices = {
        "meal": pick(lambda d: (d["diet_type"] != "non_vegetarian") & ((d["food_allergies"] != "") | (d["intolerances"] != "")),
                     lambda d: d["diet_type"] != "non_vegetarian"),
        "walk": pick(lambda d: d["post_meal_walk_habit"] == False, lambda d: d["age_yr"] > 0),   # noqa: E712
        "hypo": pick(lambda d: d["patient_id"].isin(flagged), lambda d: d["patient_id"].isin(su_ids)),
        "kidney": pick(lambda d: d["patient_id"].isin(met_ids) & (d["egfr"] < 45), lambda d: d["patient_id"].isin(met_ids) & (d["egfr"] < 45)),
    }
    lines = ["# Worked what-if examples", "",
             "_Generated by `uv run python -m twin.examples` on synthetic test patients. Every curve comes from the patient's personalised "
             "ODE twin (fitted on their first 7 days). Simulation for discussion with the patient, not a prescription._", ""]
    fig, axes = plt.subplots(2, 2, figsize=(13, 8.5))
    for ax, (story, pid) in zip(axes.flat, choices.items(), strict=True):
        obs = Observed.from_tables(tabs, pid)
        twin = E.fit(obs, pc, tcfg, lib)
        p = obs.patient
        card = twin_card(twin, obs, pc)
        day = pd.Timestamp(obs.cgm["timestamp"].min()).normalize() + pd.Timedelta(days=9)
        lines += [f"## {story.title()}: {pid} ({int(p['age_yr'])} y {p['sex']}, HbA1c {p['hba1c_pct']} %, eGFR {int(p['egfr'])}, {p['diet_type'].replace('_', '-')})",
                  "", "Patient factors considered: " + ", ".join(W.patient_factors(p, obs.meds)), "",
                  "Twin state: " + "; ".join(f"{r['label']} {r['band']} ({r['percentile']:.0f}th percentile, confidence {r['confidence']})"
                                             if r["percentile"] is not None else f"{r['label']} (no reference yet)" for r in card["rows"])
                  + f"; a standard 60 g meal raises glucose by about {card['standard_meal']['rise']:.0f} mg/dL, peaking after "
                  f"{card['standard_meal']['time_to_peak_min']} min. {card['fit_note']}.", ""]
        if story in ("meal", "walk"):
            t_now = day + pd.Timedelta(hours=20, minutes=15)
            dinner = "rice_sambar_meal" if C.check_plate(by_id["rice_sambar_meal"], p).allowed else "dal_chawal"
            plan = W.Plan(meals=[W.PlannedMeal(15, dinner)])
            st = W.state_at(twin, obs, t_now, pc, tcfg)
            if story == "meal":
                opts = C.meal_options(lib, p, "dinner")
                blocked = [(o, v) for o, v in opts if not v.allowed]
                allowed = sorted([o for o, v in opts if v.allowed and o["id"] != dinner], key=lambda o: (o["gi"] != "low", o["carbs"]))
                ivs = [W.Intervention("swap_meal", plate_id=allowed[0]["id"]), W.Intervention("scale_meal", factor=0.5)]
                if blocked:
                    ivs.append(W.Intervention("swap_meal", plate_id=blocked[0][0]["id"]))
            else:
                ivs = [W.Intervention("add_walk", start_after_min=20, duration_min=15), W.Intervention("add_walk", start_after_min=20, duration_min=30)]
            res = [W.whatif(twin, obs, t_now, plan, iv, pc, tcfg, lib, state=st) for iv in ivs]
            curves = [(f"planned: {by_id[dinner]['name']}", res[0].base, "#555")]
            cols = ["#3b6ea8", "#d9822b", "#8a5cb8"]
            lines.append(f"Plan: {by_id[dinner]['name']} at {t_now + pd.Timedelta(minutes=15):%H:%M}; predicted 5-h peak {res[0].base.peak:.0f} mg/dL.")
            for r, col in zip(res, cols, strict=False):
                if r.alt is not None:
                    curves.append((r.description, r.alt, col))
                    lines.append(f"- **{r.description}** ({r.verdict.status}): peak {r.alt.peak:.0f} mg/dL ({r.delta_peak:+.0f}); "
                                 f"minutes above 180: {r.base.minutes_above_180:.0f} -> {r.alt.minutes_above_180:.0f}. {' '.join(r.verdict.reasons)}")
                else:
                    lines.append(f"- **{r.description}**: BLOCKED - {'; '.join(r.verdict.reasons)} (not simulated)")
            lines += [f"- Safety: {res[0].safety['message']}.", ""]
            _plot(ax, curves, f"{pid}: {'meal options' if story == 'meal' else 'walk after dinner'}", t_now)
        elif story == "hypo":
            drug = obs.meds.loc[obs.meds["drug_class"] == "sulfonylurea", "drug"].iat[0]
            mx = float(tcfg["constraints"]["sulfonylurea"]["max_daily_mg"][drug])
            t_now = day + pd.Timedelta(hours=7, minutes=30)
            st = W.state_at(twin, obs, t_now, pc, tcfg)
            libd = by_id
            base = W.simulate_plan(twin, obs, st, t_now, W.Plan(meals=[W.PlannedMeal(60, "idli_sambar" if C.check_plate(libd["idli_sambar"], p).allowed else "oats_milk")]),
                                   pc, tcfg, libd, hours=8)
            risky = W.simulate_plan(twin, obs, st, t_now, W.Plan(meals=[], dose_changes={drug: mx}), pc, tcfg, libd, hours=8)
            v = C.check_drug_change(p, drug, mx, tcfg["constraints"], obs.meds)
            s = W.safety([base, risky], p, obs.meds, tcfg, tcfg["constraints"])
            lines += [f"Scenario: {drug} raised to {mx:g} mg and breakfast skipped (8 h from 07:30). Constraint check: {v.status} - {'; '.join(v.reasons) or 'no issue'}.",
                      f"- Usual morning: low {base.trough:.0f} mg/dL; scenario: low {risky.trough:.0f} mg/dL, {risky.minutes_below_70:.0f} min below 70.",
                      f"- Safety: **{s['message']}**; risk factors: {', '.join(s['risk_factors']) or 'none'}.", ""]
            _plot(ax, [("usual: breakfast + current dose", base, "#555"), (f"{drug} {mx:g} mg, breakfast skipped", risky, "#c0392b")],
                  f"{pid}: hypoglycaemia check", t_now)
        else:
            cur = float(obs.meds.loc[obs.meds["drug"] == "metformin", "daily_dose"].iat[0])
            want = min(cur + 1000, 2000)
            td_block = W.typical_day(twin, obs, {"metformin": want}, pc, tcfg)
            add = "teneligliptin" if not (obs.meds["drug_class"] == "dpp4_inhibitor").any() else "dapagliflozin"
            td = W.typical_day(twin, obs, {add: 20.0 if add == "teneligliptin" else 10.0}, pc, tcfg)
            vb = td_block["verdicts"]["metformin"]
            lines += [f"- **Metformin {cur:g} -> {want:g} mg/day**: {vb.status.upper()} - {'; '.join(vb.reasons)}"
                      + ("" if vb.allowed else " (not simulated)"),
                      f"- **Add {add}** ({td['verdicts'][add].status}{': ' + '; '.join(td['verdicts'][add].reasons) if td['verdicts'][add].reasons else ''}): "
                      f"typical-day mean glucose {td['current']['outcome'].mean:.0f} -> {td['changed']['outcome'].mean:.0f} mg/dL, "
                      f"time in range {100 * td['current']['tir']:.0f} % -> {100 * td['changed']['tir']:.0f} %, "
                      f"roughly {td['changed']['est_hba1c'] - td['current']['est_hba1c']:+.1f} HbA1c points at steady state (ADAG, rough)."
                      if td["changed"] else f"- Add {add}: blocked",
                      f"- Safety: {td['safety']['message']}.", ""]
            t0 = td["current"]["outcome"].trajectory["timestamp"].iat[0]
            curves = [("current regimen", td["current"]["outcome"], "#555")]
            if td["changed"]:
                curves.append((f"+ {add}", td["changed"]["outcome"], "#3b6ea8"))
            _plot(ax, curves, f"{pid}: typical day at steady state (metformin increase blocked, eGFR {int(p['egfr'])})", t0)
            ax.set_xlabel("hours from midnight")
    fig.tight_layout()
    RES.mkdir(parents=True, exist_ok=True)
    fig.savefig(RES / "worked_examples.png", dpi=120)
    plt.close(fig)
    lines.append("![worked examples](../results/twin/worked_examples.png)")
    (config.REPO_ROOT / "docs" / "twin_examples.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote docs/twin_examples.md and results/twin/worked_examples.png")


if __name__ == "__main__":
    main()
