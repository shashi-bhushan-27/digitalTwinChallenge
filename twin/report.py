"""Write docs/twin_report.md from results/twin (numbers from actual runs only).

    uv run python -m twin.report
"""

from __future__ import annotations

import json

from common import config

RES = config.REPO_ROOT / "results" / "twin"


def main() -> None:
    s = json.loads((RES / "summary.json").read_text(encoding="utf-8"))
    rec, fid, cf = s["recovery"], s["fidelity_heldout_rmse_median"], s["counterfactuals"]
    lines = [
        "# Twin report (Phase 3): personalised ODE twin and what-if validation",
        "",
        f"_Generated by `uv run python -m twin.report` from `results/twin/` ({s['n_patients']} synthetic test patients). This validates "
        "the twin against the simulated world only: the twin's ODE is the model that generated the data, so there is no structural "
        "model error here, unlike with real patients._",
        "",
        "## What the twin knows",
        "Only what a clinic would hold: the EHR record, prescriptions with reported adherence, CGM, wearable steps and the patient's "
        "own meal log (dish names and carb estimates, corrected for typical under-reporting; CGM rises with no logged meal are filled "
        "with a typical meal). It never reads the simulator's hidden state. The first 7 days personalise it (insulin sensitivity, "
        "beta-cell function and the fasting set point, starting from the record-based prior); later days test it.",
        "",
        "## 1. Parameter recovery (Spearman correlation with the hidden true values)",
        "",
        "| parameter | record-only prior | personalised fit |",
        "|---|---|---|",
        f"| insulin sensitivity | {rec['si_prior_vs_true']:.2f} | {rec['si_fit_vs_true']:.2f} |",
        f"| beta-cell function | {rec['beta_prior_vs_true']:.2f} | {rec['beta_fit_vs_true']:.2f} |",
        f"| product (disposition) | {rec['si_prior_x_beta_prior_vs_true_product']:.2f} | {rec['si_fit_x_beta_fit_vs_true_product']:.2f} |",
        "",
        ("The fit does **not** recover the individual parameters better than the record-based prior. The prior already uses HbA1c and the "
         "fasting glucose, which carry most of the information; from CGM and an incomplete meal log, insulin sensitivity and secretion trade "
         "off against each other and against meal-size errors. The twin card therefore shows these values with their uncertainty, and the "
         "fit is judged by what it is for: predicting glucose and the effect of changes."
         if rec["si_fit_vs_true"] < rec["si_prior_vs_true"] else
         "The fit improves on the record-based prior."),
        "",
        "## 2. Fidelity on held-out days (CGM RMSE after logged meals and at night, median across patients)",
        "",
        "| twin | RMSE (mg/dL) |",
        "|---|---|",
        f"| record-only prior | {fid['prior']:.1f} |",
        f"| personalised fit | {fid['fitted']:.1f} |",
        f"| oracle: true parameters, same observed inputs | {fid['oracle']:.1f} |",
        "",
        "Most of the remaining error is in the inputs, not the parameters: unlogged or mis-sized meals and day-to-day changes in "
        "sensitivity (sleep, stress, illness) that no twin can see.",
        "",
        "## 3. What-if answers vs true counterfactuals",
        "",
        "For one logged dinner per patient on held-out days, the twin predicts how the 5-hour peak changes under four interventions. The "
        "truth comes from replaying the same synthetic patient with the intervention applied to the true meal, true doses and true "
        "activity. The cohort-average baseline predicts every patient's change as the average true change of the others.",
        "",
        "![counterfactuals](../results/twin/counterfactuals.png)",
        "",
        "| intervention | patients | median true change (mg/dL) | MAE personalised twin | MAE record-only twin | MAE cohort average | Spearman (personalised) | sign agreement |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for name, v in cf.items():
        lines.append(f"| {name} | {v['n']} | {v['true_delta_median']:+.1f} | {v['mae_fitted']:.1f} | {v['mae_prior']:.1f} | {v['mae_cohort_average']:.1f} | "
                     f"{v['spearman_fitted']:.2f} | {100 * v['sign_agreement_fitted']:.0f} % |")
    best = [n for n, v in cf.items() if v["mae_fitted"] < min(v["mae_prior"], v["mae_cohort_average"])]
    lines += ["", f"The personalised twin beats both the record-only twin and the cohort average for: {', '.join(best) or 'none of the interventions'}."]
    if all("bias_fitted" in v for v in cf.values()):
        lines += ["", "Systematic error of the personalised twin (predicted minus true change; negative true changes mean a lower peak): "
                  + "; ".join(f"{n}: {v['bias_fitted']:+.1f} mg/dL" for n, v in cf.items())
                  + f". Its predicted dinner peak before any change is off by {next(iter(cf.values()))['base_peak_bias_fitted']:+.1f} mg/dL on average, "
                  "so large meal effects are "
                  + ("under-estimated: the twin sees smaller meals than were eaten (logged portions and unlogged extras)."
                     if next(iter(cf.values()))["base_peak_bias_fitted"] < 0 else "over-estimated.")]
    h = s.get("hypo")
    if h:
        lines += [
            "",
            "## 4. Hypoglycaemia check",
            "",
            "Scenario for every sulfonylurea user among the test patients: sulfonylurea raised to its maximum dose and breakfast skipped, "
            "8 hours from 07:30, simulated on the twin and replayed on the true patient.",
            "",
            "![hypo](../results/twin/hypo_scenario.png)",
            "",
            "| | count |",
            "|---|---|",
            f"| sulfonylurea users | {h['n_su_users']} |",
            f"| true lows (< 70 mg/dL) | {h['true_lows']} |",
            f"| lows flagged by the twin | {h['flagged_true_lows']} of {h['true_lows']} |",
            f"| true lows at least flagged as 'caution' (< 80) | {h['true_lows_with_caution_or_flag']} of {h['true_lows']} |",
            f"| false low flags | {h['false_flags']} |",
            f"| trough error (MAE) | {h['trough_mae']:.1f} mg/dL; Spearman {h['trough_spearman']:.2f} |",
        ]
    lines += [
        "",
        "## 5. Worked examples",
        "See [`twin_examples.md`](twin_examples.md): meal options with blocked choices and reasons, a post-dinner walk, a sulfonylurea "
        "hypoglycaemia warning, and a kidney-limited drug change on a typical day at steady state.",
        "",
        "## Limitations",
        "- Validated in the simulated world with a perfectly specified model; real patients add structural model error.",
        "- The twin assumes people log about 10 % fewer carbohydrates than they eat (to verify) and fills unlogged CGM rises with a typical meal.",
        "- Day-to-day changes in insulin sensitivity are invisible to the twin; what-if answers are for an average day for this patient.",
        "- Drug-regimen answers compare typical days at steady state; they are not titration advice. All rules await clinical review "
        "(`docs/clinical_rules_to_review.md`).",
    ]
    (config.REPO_ROOT / "docs" / "twin_report.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote docs/twin_report.md")


if __name__ == "__main__":
    main()
