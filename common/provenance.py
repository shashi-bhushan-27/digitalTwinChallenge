"""List every literature value or assumption in configs/ that still needs checking.

    uv run python -m common.provenance      # writes docs/parameters_to_verify.md
"""

from __future__ import annotations

from common.config import CONFIG_DIR, REPO_ROOT, collect_provenance, load_raw


def main() -> None:
    rows = []
    for path in sorted(CONFIG_DIR.glob("*.yaml")):
        if path.stem == "calibrated":
            continue
        for rec in collect_provenance(load_raw(path.name)):
            rows.append((path.name, rec))
    unverified = [(f, r) for f, r in rows if not r.verified]
    lines = [
        "# Parameters to verify against source",
        "",
        "_Generated by `uv run python -m common.provenance` from the provenance tags in `configs/`. "
        "Do not edit by hand; mark a value `verified: true` in its config only after checking the cited source._",
        "",
        f"{len(unverified)} of {len(rows)} tagged values are unverified. Until checked, quote them as assumptions, not facts.",
        "",
        "| config | parameter | value | source / what to check |",
        "|---|---|---|---|",
    ]
    for f, r in rows:
        if r.verified:
            continue
        val = (r.details if r.value is None else str(r.value)).replace("|", "/")
        lines.append(f"| {f} | `{r.path}` | {val} | {r.source.replace('|', '/')} |")
    out = REPO_ROOT / "docs" / "parameters_to_verify.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out} ({len(unverified)} unverified)")


if __name__ == "__main__":
    main()
